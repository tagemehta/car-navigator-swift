#!/usr/bin/env python3
"""Generate per-tool agent config from the tool-neutral sources in .agents/.

Sources of truth (edit these):
  AGENTS.md                      always-on rules (Devin + Codex read natively; CLAUDE.md imports it)
  .agents/skills/<name>/SKILL.md skills (Devin + Codex read natively)
  .agents/roles/<name>.md        subagent roles

Generated (never edit by hand):
  .devin/agents/<name>.md        Devin custom subagent profiles
  .claude/agents/<name>.md       Claude Code subagents
  .codex/agents/<name>.toml      Codex custom agents
  .claude/skills/<name>          symlinks -> .agents/skills/<name> (Claude Code only reads .claude/skills)

Usage:
  python3 scripts/sync_agent_config.py          # write generated files
  python3 scripts/sync_agent_config.py --check  # exit 1 if anything is out of date
"""

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES = ROOT / ".agents" / "roles"
SKILLS = ROOT / ".agents" / "skills"
MARKER = "GENERATED by scripts/sync_agent_config.py"

# access level -> tool allowlist per tool (None = inherit all tools)
TOOLS = {
    "read": {"devin": ["read", "grep", "glob"], "claude": "Read, Grep, Glob"},
    "read-exec": {"devin": ["read", "grep", "glob", "exec"], "claude": "Read, Grep, Glob, Bash"},
    "write": {"devin": None, "claude": None},
}


def parse_role(path):
    text = path.read_text()
    if not text.startswith("---\n"):
        sys.exit(f"{path}: missing frontmatter")
    header, body = text[4:].split("\n---\n", 1)
    meta = dict(line.split(":", 1) for line in header.splitlines() if line.strip())
    meta = {k.strip(): v.strip() for k, v in meta.items()}
    for key in ("name", "description", "access"):
        if key not in meta:
            sys.exit(f"{path}: frontmatter needs '{key}'")
    if meta["access"] not in TOOLS:
        sys.exit(f"{path}: access must be one of {sorted(TOOLS)}")
    if "'''" in body:
        sys.exit(f"{path}: body may not contain ''' (breaks TOML)")
    return meta, body.strip() + "\n"


def note(src):
    return f"<!-- {MARKER} from {src}; edit the source and re-run. -->\n\n"


def yaml_header(meta):
    return ["---", f"name: {meta['name']}", f"description: {json.dumps(meta['description'])}"]


def devin_md(meta, body, src):
    lines = yaml_header(meta)
    tools = TOOLS[meta["access"]]["devin"]
    if tools:
        lines += ["allowed-tools:"] + [f"  - {t}" for t in tools]
    return "\n".join(lines + ["---", ""]) + note(src) + body


def claude_md(meta, body, src):
    lines = yaml_header(meta)
    tools = TOOLS[meta["access"]]["claude"]
    if tools:
        lines.append(f"tools: {tools}")
    return "\n".join(lines + ["---", ""]) + note(src) + body


def codex_toml(meta, body, src):
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    access = {"read": "Do not edit files or run commands with side effects.\n\n",
              "read-exec": "Do not edit files.\n\n", "write": ""}[meta["access"]]
    return (f"# {MARKER} from {src}; edit the source and re-run.\n"
            f'name = "{esc(meta["name"])}"\n'
            f'description = "{esc(meta["description"])}"\n'
            f"developer_instructions = '''\n{access}{body}'''\n")


def desired_files():
    out = {}
    for path in sorted(ROLES.glob("*.md")):
        meta, body = parse_role(path)
        src = path.relative_to(ROOT).as_posix()
        name = meta["name"]
        out[ROOT / ".devin" / "agents" / f"{name}.md"] = devin_md(meta, body, src)
        out[ROOT / ".claude" / "agents" / f"{name}.md"] = claude_md(meta, body, src)
        out[ROOT / ".codex" / "agents" / f"{name}.toml"] = codex_toml(meta, body, src)
    return out


def desired_links():
    return {ROOT / ".claude" / "skills" / d.name: Path("..", "..", ".agents", "skills", d.name)
            for d in sorted(SKILLS.iterdir()) if (d / "SKILL.md").is_file()}


def stale_generated(want_files):
    for d, pattern in ((".devin/agents", "*.md"), (".claude/agents", "*.md"), (".codex/agents", "*.toml")):
        for path in (ROOT / d).glob(pattern):
            if path not in want_files and MARKER in path.read_text():
                yield path


def stale_links(want_links):
    for path in (ROOT / ".claude" / "skills").glob("*"):
        if path.is_symlink() and path not in want_links and ".agents/skills" in os.readlink(path):
            yield path


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report drift without writing")
    args = parser.parse_args()

    files, links = desired_files(), desired_links()
    drift = []
    for path, content in files.items():
        if not path.exists() or path.read_text() != content:
            drift.append(f"write   {path.relative_to(ROOT)}")
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    for link, target in links.items():
        if link.is_symlink() and Path(os.readlink(link)) == target:
            continue
        if link.exists() and not link.is_symlink():
            sys.exit(f"{link.relative_to(ROOT)} is a real directory; move it to .agents/skills/ first")
        drift.append(f"link    {link.relative_to(ROOT)} -> {target}")
        if not args.check:
            link.parent.mkdir(parents=True, exist_ok=True)
            if link.is_symlink():
                link.unlink()
            link.symlink_to(target, target_is_directory=True)
    for path in [*stale_generated(files), *stale_links(links)]:
        drift.append(f"remove  {path.relative_to(ROOT)}")
        if not args.check:
            path.unlink()

    print("\n".join(drift) if drift else "agent config in sync")
    sys.exit(1 if args.check and drift else 0)


if __name__ == "__main__":
    main()
